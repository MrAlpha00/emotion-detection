def _existing_columns(inspector, table_name):
    """Return the set of column names currently present on a table."""
    return {col['name'] for col in inspector.get_columns(table_name)}


def _existing_indexes(inspector, table_name):
    """Return the set of index names currently present on a table."""
    return {idx['name'] for idx in inspector.get_indexes(table_name)}


def _table_definitions():
    """Map table name -> the sa.Table definition used with batch_alter_table."""
    return {
        'users': _USERS,
        'detections': _DETECTIONS,
        'live_sessions': _LIVE_SESSIONS,
        'user_activities': _USER_ACTIVITIES,
    }


def _nullable_columns(inspector, table_name, candidates):
    """Return the subset of ``candidates`` that exist and are still nullable."""
    existing = {col['name']: col for col in inspector.get_columns(table_name)}
    return [
        name for name in candidates
        if name in existing and existing[name].get('nullable')
    ]


def _foreign_keys_lack_cascade(inspector, table_name):
    """
    True when a users foreign key is missing ON DELETE CASCADE.

    The legacy tables were created before ondelete='CASCADE' reached the models.
    """
    for fk in inspector.get_foreign_keys(table_name):
        if fk.get('referred_table') != 'users':
            continue
        if not (fk.get('options') or {}).get('ondelete'):
            return True
    return False


def _enforce_constraints(inspector):
    """
    Rebuild the legacy tables that do not yet match the models.

    SQLite cannot ALTER a constraint in place, so Alembic's batch mode recreates
    each affected table from the definition above. This is the one place the
    upgrade is not purely additive, so it is driven by inspection and only runs
    for tables that actually need it - a database that is already correct is left
    completely alone. Child tables are rebuilt before parents because SQLite
    tracks foreign key references by table name.
    """
    definitions = _table_definitions()

    # rebuild[table] = set of columns to flip to NOT NULL. A table is rebuilt when
    # it appears here at all, including when the set is empty (that is the
    # foreign-key-only case), so the key is what matters, not the set's truthiness.
    rebuild = {}

    for table_name in ('detections', 'live_sessions'):
        if _foreign_keys_lack_cascade(inspector, table_name):
            rebuild[table_name] = set()

    not_null_targets = {
        'users': ('created_at', 'updated_at'),
        'live_sessions': ('created_at',),
    }
    for table_name, candidates in not_null_targets.items():
        found = _nullable_columns(inspector, table_name, candidates)
        if found:
            rebuild.setdefault(table_name, set()).update(found)

    # A batch rebuild with no queued operations is a no-op in Alembic: it never
    # recreates the table. So when a table needs rebuilding purely for its
    # foreign key, re-assert NOT NULL on the FK column. That is idempotent and it
    # guarantees the table is actually recreated from `copy_from`, which is what
    # carries ON DELETE CASCADE.
    for columns in rebuild.values():
        if not columns:
            columns.add('user_id')

    # Children first: users is referenced by all three other tables.
    for table_name in ('user_activities', 'live_sessions', 'detections', 'users'):
        if table_name not in rebuild:
            continue
        with op.batch_alter_table(table_name, copy_from=definitions[table_name]) as batch:
            for column in sorted(rebuild[table_name]):
                batch.alter_column(
                    column,
                    existing_type=(
                        sa.Integer() if column == 'user_id' else sa.DateTime()
                    ),
                    nullable=False,
                )


def _create_everything(bind):
    """Create the full schema on an empty database."""
    # _META.create_all() emits CREATE TABLE in dependency order and resolves the
    # foreign keys, then the indexes are added.
    _META.create_all(bind)
    for name, table_name, columns, unique in _INDEXES:
        op.create_index(name, table_name, columns, unique=unique)


def _upgrade_legacy(bind, inspector):
    """
    Bring a pre-Alembic schema up to date using additive changes only.

    Every step is guarded by an existence check so a partially upgraded file can
    be run through again without error.
    """
    for table_name, column_name, column in _NEW_COLUMNS:
        if not inspector.has_table(table_name):
            continue
        if column_name in _existing_columns(inspector, table_name):
            continue
        op.add_column(table_name, column.copy())

    # Bring pre-existing constraints in line with the models BEFORE creating
    # indexes: SQLite batch mode recreates each table from `copy_from`, and index
    # definitions are not part of that, so any index created beforehand would be
    # lost with the old table.
    _enforce_constraints(inspector)

    # The rebuilds above replaced tables, so anything the inspector reported
    # earlier is stale. Re-inspect before deciding which indexes are missing.
    inspector = sa.inspect(bind)

    for name, table_name, columns, unique in _INDEXES:
        if not inspector.has_table(table_name):
            continue
        if name in _existing_indexes(inspector, table_name):
            continue
        op.create_index(name, table_name, columns, unique=unique)


def upgrade():
    bind = op.get_bind()
    inspector = sa.inspect(bind)

    if inspector.has_table('users'):
        _upgrade_legacy(bind, inspector)
    else:
        _create_everything(bind)


def _any_rows(bind, table_names):
    """True when at least one of the given tables holds a row."""
    for name in table_names:
        result = bind.execute(
            sa.text(f'SELECT 1 FROM "{name}" LIMIT 1')
        ).fetchone()
        if result:
            return True
    return False


def downgrade():
    """
    Reverse this revision.

    Two cases, told apart by whether any table still holds rows:

    * **No rows anywhere** - the schema was created by this revision on an empty
      database, so the whole thing is removed.
    * **Rows present** - this was a pre-existing legacy database. Only the
      additive changes are reversed and the original tables and data are left in
      place.

    Column drops go through batch mode because SQLite cannot DROP COLUMN
    without recreating the table. Column drops therefore run before the index
    drops, since those recreations discard the indexes anyway.
    """
    bind = op.get_bind()
    table_names = [table.name for table in _TABLES]

    if not _any_rows(bind, table_names):
        _META.drop_all(bind)
        return

    # Legacy database: drop only what this revision added, children first so the
    # foreign keys they declare stay valid while the rebuilds happen.
    #
    # copy_from is supplied on purpose. With a bare table name Alembic reflects
    # the target shape itself, and in this schema that reflection produced a
    # mismatched column list (it reached for live_sessions.session_token while
    # rebuilding detections), which failed halfway and left an
    # _alembic_tmp_<table> table behind. Naming the intended shape explicitly
    # keeps the rebuild deterministic on both SQLite and PostgreSQL.
    definitions = _table_definitions()
    for table_name in ('detections', 'live_sessions', 'users'):
        inspector = sa.inspect(bind)
        present = [
            column_name
            for _table, column_name, _column in _NEW_COLUMNS
            if _table == table_name
            and column_name in _existing_columns(inspector, table_name)
        ]
        if not present:
            continue
        with op.batch_alter_table(
            table_name, copy_from=definitions[table_name]
        ) as batch:
            for column_name in present:
                batch.drop_column(column_name)

    inspector = sa.inspect(bind)
    for name, table_name, _columns, _unique in reversed(_INDEXES):
        if not inspector.has_table(table_name):
            continue
        if name not in _existing_indexes(inspector, table_name):
            continue
        op.drop_index(name, table_name=table_name)
