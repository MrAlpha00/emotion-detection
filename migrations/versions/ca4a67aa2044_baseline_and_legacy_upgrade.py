"""baseline schema, plus upgrade path for the legacy SQLite database

Revision ID: ca4a67aa2044
Revises:
Create Date: 2026-10-05

WHY ONE REVISION DOES TWO JOBS
-------------------------------
This is the first Alembic revision in the project, so it has to serve two
different starting points:

1. A **brand new PostgreSQL database** (the production case). Nothing exists
   yet, so the full current schema is created.
2. The **legacy local SQLite file** ``database/emotion_app.db``, written by
   ``db.create_all()`` before Alembic existed. It already holds real rows but is
   missing the columns and indexes added since.

``upgrade()`` inspects the database and picks the right path, so a fresh
deployment and an in-place upgrade end up on the same schema.

DESIGN CONSTRAINTS
------------------
* **Additive only on the upgrade path.** No SQLite table is rebuilt and no
  column is dropped or retyped, so upgrading cannot lose existing rows.
  Alembic's autogenerated output tried to drop and recreate unnamed foreign
  keys and to flip columns to NOT NULL; on SQLite those need a table rebuild and
  the unnamed-FK directives fail outright.
* **No invented data.** New columns get the same server-side default the model
  applies in Python, so pre-existing rows read back with a meaningful non-null
  value instead of NULL.
* **Idempotent index creation.** An index is only created when the inspector
  reports it missing.

ON DELETE CASCADE: the legacy SQLite tables predate the ``ondelete='CASCADE'``
clauses in the models, so this revision does not rebuild them to attach
database-level cascades. That is not a correctness gap: ``User.detections`` and
``User.live_sessions`` both use ``cascade='all, delete-orphan'`` with
``passive_deletes=False``, so SQLAlchemy issues the deletes. Freshly created
databases do get the database-level cascade.
"""

